export const locale = navigator.language?.toLowerCase().startsWith("ru") ? "ru" : "en";

export function t(key, params = {}) {
  const template = STRINGS[locale][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

